import {randomUUID} from 'node:crypto';
import {cp,mkdir,readFile,readdir,rm,stat,writeFile} from 'node:fs/promises';
import {join,relative,resolve,sep} from 'node:path';
import {assertRegularTree} from './pipeline.ts';
import {packFingerprint} from './pack-fingerprint.ts';
import {nativeConfig,validateBindings,FACE_WORDS,MOTION_WORDS} from '../workbench/tools/native-catalog.mjs';

export const LIBRARY = 'native-library.json';
export async function writeNativePack(root:string,catalog:any,bindings:any[],preview=false) {
  const native=nativeConfig(catalog,bindings,{includeAll:preview});
  const dirs=await readdir(join(root,'models'),{withFileTypes:true});let count=0;
  for(const dir of dirs.filter(d=>d.isDirectory())) {
    const file=join(root,'models',dir.name,'profile.js');
    let text=await readFile(file,'utf8');
    // Only profiles generated by this converter; never evaluate a model script.
    if(!/^\s*(?:\/\*[\s\S]*?\*\/\s*)?export default \{/.test(text))throw Error('这份形象包不支持动作编辑');
    text=text.replace(/^  native: .*\r?\n/gm,'');
    text=text.replace(/\r?\n};\s*$/,`\n  native: ${JSON.stringify(native)},\n};\n`);
    await writeFile(file,text);count++;
  }
  if(count!==1)throw Error('请为单个 Live2D 模型编辑动作');
  if(!preview){
    const file=join(root,'figure.json'),manifest=JSON.parse(await readFile(file,'utf8'));
    const previous=await readFile(join(root,LIBRARY),'utf8').then(s=>JSON.parse(s).bindings||[]).catch(()=>[]);
    const removed=new Set(previous.map((b:any)=>b.word).filter((w:string)=>MOTION_WORDS.includes(w)));
    manifest.vocab=(manifest.vocab||[]).filter((v:any)=>!removed.has(v.id));
    for(const b of bindings)if(!manifest.vocab.some((v:any)=>v.id===b.word)){
      const resource=catalog.resources.find((r:any)=>r.id===b.resource);
      manifest.vocab.push({id:b.word,kind:resource.kind==='expression'?'expression':'motion',names:{zh:[b.word],en:[b.word]},seconds:resource.seconds});
    }
    await writeFile(file,JSON.stringify(manifest,null,2)+'\n');
    await writeFile(join(root,LIBRARY),JSON.stringify({version:1,catalog,bindings}));
  }
}

export class ManualSessions {
  sessions=new Map<string,any>();
  private root:string;
  private workbench:string;
  constructor(root:string,workbench:string){this.root=root;this.workbench=workbench;}
  async open(pack:string,catalog:any,bindings:any[]=[],source?:any,buildId?:string){
    if(this.sessions.size>=3)throw Error('请先关闭已有动作编辑窗口');
    await assertRegularTree(pack);
    const token=randomUUID(),dir=join(this.root,'manual-preview',token),copy=join(dir,'pack');
    try{
      await mkdir(dir,{recursive:true});await cp(pack,copy,{recursive:true});
      // The preview always uses this version's trusted renderer, including old generated packs.
      for(const file of ['live2d.js','native-actions.js','render-config.js','render-quality.js','role-values.js','soullink.js'])
        await cp(join(this.workbench,'pack','backends',file),join(copy,'backends',file));
      await writeNativePack(copy,catalog,bindings,true);
      await cp(join(this.workbench,'vendor','coo-kit','kit'),join(dir,'kit'),{recursive:true});
      const files:Array<{path:string;size:number}>=[];let bytes=0;
      const walk=async(base:string)=>{for(const e of await readdir(base,{withFileTypes:true})){
        const path=join(base,e.name);if(e.isDirectory())await walk(path);
        else {const size=(await stat(path)).size;bytes+=size;files.push({path:relative(dir,path).split(sep).join('/'),size});}
      }};await walk(dir);
      if(bytes>512*1048576||files.length>1000)throw Error('预览资源过大');
      const value={token,dir,pack,catalog,bindings,source,buildId,hash:await packFingerprint(pack),at:Date.now(),files};
      this.sessions.set(token,value);
      return {token,title:catalog.model.title,fingerprint:catalog.fingerprint,bindings,files,
        words:{expressions:FACE_WORDS,motions:MOTION_WORDS},
        resources:catalog.resources.map(({id,title,kind,classification,seconds,release}:any)=>({id,title,kind,classification,seconds,release})),warnings:catalog.warnings||[],truncated:catalog.truncated};
    }catch(e){await rm(dir,{recursive:true,force:true});throw e;}
  }
  get(token:string){const s=this.sessions.get(token);if(!s||Date.now()-s.at>2*3600000)throw Error('编辑已过期，请重新打开');s.at=Date.now();return s;}
  async asset(token:string,path:string,offset:number){
    const s=this.get(token),file=s.files.find((f:any)=>f.path===path);
    if(!file||!Number.isInteger(offset)||offset<0||offset>file.size)throw Error('预览资源无效');
    const target=resolve(s.dir,path);if(!target.startsWith(resolve(s.dir)+sep))throw Error('预览路径无效');
    const bytes=await readFile(target);return {b64:bytes.subarray(offset,offset+1048576).toString('base64')};
  }
  async validate(token:string,bindings:any[]){
    const s=this.get(token);await assertRegularTree(s.pack);
    if(await packFingerprint(s.pack)!==s.hash)throw Error('形象包已变化，请重新打开编辑');
    return {session:s,bindings:validateBindings(s.catalog,bindings)};
  }
  async close(token:string){const s=this.sessions.get(token);if(s){this.sessions.delete(token);await rm(s.dir,{recursive:true,force:true});if(s.ownedRoot)await rm(s.ownedRoot,{recursive:true,force:true});}}
  async stop(){for(const key of this.sessions.keys())await this.close(key);}
}
